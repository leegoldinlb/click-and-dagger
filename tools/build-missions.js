#!/usr/bin/env node
'use strict';
// Bundles every missions/*.json into js/missions.js as a plain `MISSIONS` object,
// so world.js's boot sequence can look one up synchronously (no fetch/async
// restructuring needed). Run this after adding/editing anything in missions/,
// before committing — index.html and editor.html load js/missions.js before
// world.js, so it must be regenerated whenever missions/ changes.
//
// Usage: node tools/build-missions.js

const fs = require('fs');
const path = require('path');

const missionsDir = path.join(__dirname, '..', 'missions');
const outFile = path.join(__dirname, '..', 'js', 'missions.js');

// Mission ids must match the hub gate's missionLink value (editor.js's
// MISSION_CITIES) to actually be reachable — filenames are normalized to
// lowercase, plus a couple of aliases where the natural filename doesn't
// match the gate id (Havana → cuba, NYC → newyork).
const ALIASES = { havana: 'cuba', nyc: 'newyork' };

const files = fs.readdirSync(missionsDir).filter(f => f.endsWith('.json')).sort();
const missions = {};
for (const f of files) {
  const base = f.replace(/\.json$/, '').toLowerCase();
  const id = ALIASES[base] || base;
  const raw = fs.readFileSync(path.join(missionsDir, f), 'utf8');
  try {
    missions[id] = JSON.parse(raw);
  } catch (e) {
    console.error('Failed to parse missions/' + f + ':', e.message);
    process.exit(1);
  }
}

const out = "'use strict';\n" +
  "// Auto-generated by tools/build-missions.js from missions/*.json — do not edit by hand.\n" +
  "// Regenerate after changing anything in missions/, before committing.\n" +
  'const MISSIONS = ' + JSON.stringify(missions) + ';\n';

fs.writeFileSync(outFile, out);
console.log('Wrote js/missions.js with ' + files.length + ' mission(s): ' + Object.keys(missions).join(', '));
